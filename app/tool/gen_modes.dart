// Writes lib/modes/builtin_modes.g.dart: every file of every mode in
// ../modes (mode.yaml, node.lua, field.lua, assets/screens/*.yaml) as Dart
// strings, so an Android prop carries the same modes as a Field Box (whose
// firmware compiles them in: decision A11). Run from app/:
//
//     dart run tool/gen_modes.dart          (python tools/docker_app.py gen)
//
// test/modes/builtin_modes_test.dart fails when the file is out of date.

import 'dart:io';

/// The files of a mode folder that the app needs, relative to it.
List<String> modeFiles(Directory mode) {
  final out = <String>[];
  for (final name in ['mode.yaml', 'node.lua', 'field.lua']) {
    if (File('${mode.path}/$name').existsSync()) out.add(name);
  }
  final screens = Directory('${mode.path}/assets/screens');
  if (screens.existsSync()) {
    final names =
        screens
            .listSync()
            .whereType<File>()
            .map((f) => f.uri.pathSegments.last)
            .where((n) => n.endsWith('.yaml'))
            .toList()
          ..sort();
    out.addAll(names.map((n) => 'assets/screens/$n'));
  }
  return out;
}

/// The mode folders under [root] (those with a mode.yaml), sorted.
List<Directory> modeFolders(Directory root) =>
    root
        .listSync()
        .whereType<Directory>()
        .where((d) => File('${d.path}/mode.yaml').existsSync())
        .toList()
      ..sort((a, b) => a.path.compareTo(b.path));

String dartString(String s) {
  final out = StringBuffer("'");
  for (final r in s.runes) {
    switch (r) {
      case 0x5c:
        out.write(r'\\');
      case 0x27:
        out.write(r"\'");
      case 0x24:
        out.write(r'\$');
      case 0x0a:
        out.write(r'\n');
      case 0x0d:
        out.write(r'\r');
      case 0x09:
        out.write(r'\t');
      default:
        if (r < 0x20) {
          out.write('\\u{${r.toRadixString(16)}}');
        } else {
          out.writeCharCode(r);
        }
    }
  }
  out.write("'");
  return out.toString();
}

String generate(Directory root) {
  final out = StringBuffer()
    // The tags are split so that REUSE does not read them as this file's own.
    ..writeln(
      '// SPDX-'
      'FileCopyrightText: 2026 The Atalaia contributors',
    )
    ..writeln(
      '// SPDX-'
      'License-Identifier: GPL-3.0-or-later',
    )
    ..writeln()
    ..writeln('// GENERATED by tool/gen_modes.dart from modes/: do not edit.')
    ..writeln(
      '// Each mode file carries its own SPDX header; REUSE skips them.',
    )
    ..writeln()
    ..writeln('/// The built-in modes: folder name, then path in the folder,')
    ..writeln("/// then the file's text.")
    ..writeln('library;')
    ..writeln()
    ..writeln(
      '// REUSE-'
      'IgnoreStart',
    )
    ..writeln('const Map<String, Map<String, String>> builtinModeFiles = {');
  for (final mode in modeFolders(root)) {
    final folder = mode.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
    out.writeln('  ${dartString(folder)}: {');
    for (final f in modeFiles(mode)) {
      final text = File('${mode.path}/$f').readAsStringSync();
      out.writeln('    ${dartString(f)}: ${dartString(text)},');
    }
    out.writeln('  },');
  }
  out
    ..writeln('};')
    ..writeln(
      '// REUSE-'
      'IgnoreEnd',
    );
  return out.toString();
}

void main(List<String> args) {
  final root = Directory(args.isNotEmpty ? args.first : '../modes');
  final target = File('lib/modes/builtin_modes.g.dart');
  target.writeAsStringSync(generate(root));
  stdout.writeln('wrote ${target.path}');
}
