def gen_c_header(s: dict[str, Any]) -> str:
    L = c_spdx("Skirmesh-RF protocol constants, ids and keys. See protocol/README.md.")
    L += ["#ifndef ATALAIA_PROTOCOL_H", "#define ATALAIA_PROTOCOL_H", "",
          "#include <stdbool.h>", "#include <stddef.h>", "#include <stdint.h>", "",
          "/* Skirmesh-RF protocol version spoken by this core. */",
          f"#define ATALAIA_PROTOCOL_VERSION {s['version']}", "",
          "/* ---- LoRa packet ---- */", ""]
    rows = [("#define ATALAIA_RF_HEADER_BYTES", str(s["header_bytes"])),
            ("#define ATALAIA_RF_PAYLOAD_MAX", f"{s['payload_max']} /* CBOR with integer keys */"),
            ("#define ATALAIA_RF_MIC_BYTES", str(s["mic_bytes"]))]
    L += aligned(rows, "")
    L += ["", "/* Header field offsets; every field has its size in _BYTES. */"]
    rows = []
    for f in s["header"]:
        n = c_ident(f["name"])
        rows.append((f"#define ATALAIA_RF_{n}_OFFSET", f"{f['offset']} /* {c_comment(f['doc'])} */"))
        rows.append((f"#define ATALAIA_RF_{n}_BYTES", str(f["bytes"])))
    L += aligned(rows, "")
    L += ["", "typedef enum {"]
    rows = [(f"ATALAIA_MSG_{c_ident(m['name'])} = {m['id']},", f"/* {c_comment(m['doc'])} */")
            for m in s["messages"]]
    L += aligned(rows)
    L += ["} atalaia_msg_type_t;", ""]
    for msg_name, pfields in s.get("payloads", {}).items():
        L += [f"/* CBOR keys of {msg_name} payload fields. */", "enum {"]
        rows = [(f"ATALAIA_PL_{c_ident(msg_name)}_{c_ident(f['name'])} = {f['key']},",
                 f"/* {c_comment(f['doc'])} */") for f in pfields]
        L += aligned(rows)
        L += ["};", ""]
    L += ["/* ---- Events ---- */", "",
          "/* Longest event type name plus the terminating NUL. */",
          f"#define ATALAIA_EVENT_TYPE_MAX {s['type_max'] + 1}", "",
          "typedef enum {"]
    items = list(s["prios"].items())
    rows = [(f"ATALAIA_PRIO_{c_ident(k)} = {v['value']}{',' if i < len(items) - 1 else ''}",
             f"/* {c_comment(v['doc'])} */") for i, (k, v) in enumerate(items)]
    L += aligned(rows)
    L += ["} atalaia_prio_t;", "", "/* CBOR keys of the event envelope. */", "enum {"]
    rows = [(f"ATALAIA_KEY_{c_ident(k)} = {v['key']},", f"/* {c_comment(v['doc'])} */")
            for k, v in s["envelope"].items()]
    L += aligned(rows)
    L += ["};", "", "/* CBOR keys of event data fields. */", "enum {"]
    rows = [(f"ATALAIA_DATA_{c_ident(k)} = {v['key']},", f"/* {c_comment(v['doc'])} */")
            for k, v in s["fields"].items()]
    L += aligned(rows)
    L += ["};", "", "/* Standard event ids: the CBOR value of the type field. */", "enum {"]
    rows = [(f"ATALAIA_EV_{c_ident(k)} = {v['id']},", f"/* {k} */") for k, v in s["events"].items()]
    L += aligned(rows)
    L += ["};", "",
          "typedef enum {",
          "    ATALAIA_FIELD_STRING,",
          "    ATALAIA_FIELD_INTEGER,",
          "    ATALAIA_FIELD_NUMBER,",
          "    ATALAIA_FIELD_BOOLEAN",
          "} atalaia_field_type_t;",
          "",
          "typedef struct {",
          "    const char *name;",
          "    uint8_t key;",
          "    atalaia_field_type_t type;",
          "    bool common; /* allowed in every event */",
          "} atalaia_data_field_def_t;",
          "",
          "typedef struct {",
          "    const char *name;",
          "    uint8_t id;",
          "    atalaia_prio_t prio;  /* default priority */",
          "    const uint8_t *data;  /* keys of the data fields it may carry, */",
          "    uint8_t data_count;   /* besides the common ones */",
          "} atalaia_event_def_t;",
          "",
          "extern const atalaia_event_def_t atalaia_event_defs[];",
          "extern const size_t atalaia_event_def_count;",
          "extern const atalaia_data_field_def_t atalaia_data_field_defs[];",
          "extern const size_t atalaia_data_field_def_count;",
          "",
          "/* The standard event with this name or id; NULL for custom events. */",
          "const atalaia_event_def_t *atalaia_event_def(const char *name);",
          "const atalaia_event_def_t *atalaia_event_def_by_id(unsigned id);",
          "",
          "/* The data field with this name (len bytes, no NUL needed) or key. */",
          "const atalaia_data_field_def_t *atalaia_data_field(const char *name, size_t len);",
          "const atalaia_data_field_def_t *atalaia_data_field_by_key(unsigned key);",
          "",
          "/* \"HELLO\", \"EVENT\", ... or NULL for an unknown message type. */",
          "const char *atalaia_msg_type_name(unsigned type);",
          "",
          "#endif /* ATALAIA_PROTOCOL_H */",
          ""]
    return "\n".join(L)


def gen_c_source(s: dict[str, Any]) -> str:
    L = c_spdx("Skirmesh-RF protocol tables and lookups.")
    L += ["#include <string.h>", "", '#include "atalaia/protocol.h"', ""]
    fields = s["fields"]
    for name, e in s["events"].items():
        if e.get("data"):
            keys = ", ".join(str(fields[d]["key"]) for d in e["data"])
            L.append(f"static const uint8_t data_{c_ident(name).lower()}[] = {{{keys}}};")
    L += ["", "const atalaia_event_def_t atalaia_event_defs[] = {"]
    for name, e in s["events"].items():
        prio = f"ATALAIA_PRIO_{c_ident(e['prio'])}"
        ident = f"ATALAIA_EV_{c_ident(name)}"
        if e.get("data"):
            arr = f"data_{c_ident(name).lower()}"
            L.append(f"    {{{c_string(name)}, {ident}, {prio}, {arr}, {len(e['data'])}}},")
        else:
            L.append(f"    {{{c_string(name)}, {ident}, {prio}, NULL, 0}},")
    L += ["};", "const size_t atalaia_event_def_count =",
          "    sizeof(atalaia_event_defs) / sizeof(atalaia_event_defs[0]);", "",
          "const atalaia_data_field_def_t atalaia_data_field_defs[] = {"]
    for name, f in fields.items():
        common = "true" if f.get("common") else "false"
        L.append(f"    {{{c_string(name)}, ATALAIA_DATA_{c_ident(name)}, "
                 f"ATALAIA_FIELD_{c_ident(f['type'])}, {common}}},")
    L += ["};", "const size_t atalaia_data_field_def_count =",
          "    sizeof(atalaia_data_field_defs) / sizeof(atalaia_data_field_defs[0]);", "",
          "const atalaia_event_def_t *atalaia_event_def(const char *name)",
          "{",
          "    for (size_t i = 0; name != NULL && i < atalaia_event_def_count; i++) {",
          "        if (strcmp(atalaia_event_defs[i].name, name) == 0) {",
          "            return &atalaia_event_defs[i];",
          "        }",
          "    }",
          "    return NULL;",
          "}",
          "",
          "const atalaia_event_def_t *atalaia_event_def_by_id(unsigned id)",
          "{",
          "    for (size_t i = 0; i < atalaia_event_def_count; i++) {",
          "        if (atalaia_event_defs[i].id == id) {",
          "            return &atalaia_event_defs[i];",
          "        }",
          "    }",
          "    return NULL;",
          "}",
          "",
          "const atalaia_data_field_def_t *atalaia_data_field(const char *name, size_t len)",
          "{",
          "    for (size_t i = 0; name != NULL && i < atalaia_data_field_def_count; i++) {",
          "        const char *n = atalaia_data_field_defs[i].name;",
          "        if (strlen(n) == len && memcmp(n, name, len) == 0) {",
          "            return &atalaia_data_field_defs[i];",
          "        }",
          "    }",
          "    return NULL;",
          "}",
          "",
          "const atalaia_data_field_def_t *atalaia_data_field_by_key(unsigned key)",
          "{",
          "    for (size_t i = 0; i < atalaia_data_field_def_count; i++) {",
          "        if (atalaia_data_field_defs[i].key == key) {",
          "            return &atalaia_data_field_defs[i];",
          "        }",
          "    }",
          "    return NULL;",
          "}",
          "",
          "const char *atalaia_msg_type_name(unsigned type)",
          "{",
          "    switch (type) {"]
    for m in s["messages"]:
        L.append(f"    case ATALAIA_MSG_{c_ident(m['name'])}: return {c_string(m['name'])};")
    L += ["    default: return NULL;", "    }", "}", ""]
    return "\n".join(L)


def gen_c_vectors(s: dict[str, Any], vectors: dict[str, Any]) -> str:
    L = c_spdx("Codec test vectors from protocol/vectors/events.yaml.")
    L[5] = " * Generated by tools/protogen.py from protocol/vectors/. Do not edit."
    L += ["#ifndef ATALAIA_PROTOCOL_VECTORS_H", "#define ATALAIA_PROTOCOL_VECTORS_H", "",
          "#include <stddef.h>", "#include <stdint.h>", "", '#include "atalaia/event.h"', "",
          "typedef struct {",
          "    const char *name;",
          "    atalaia_event_t event;",
          "    const char *data_json;",
          "    const uint8_t *cbor;",
          "    size_t cbor_len;",
          "} protocol_vector_t;",
          "",
          "typedef struct {",
          "    const char *name;",
          "    const uint8_t *cbor;",
          "    size_t cbor_len;",
          "} protocol_bad_vector_t;",
          ""]

    def byte_array(name: str, hexstr: str) -> list[str]:
        data = bytes.fromhex(hexstr)
        out = [f"static const uint8_t {name}[] = {{"]
        for i in range(0, len(data), 12):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
        out.append("};")
        return out

    for i, v in enumerate(vectors["valid"]):
        L += byte_array(f"vector_{i}_cbor", v["cbor"])
    for i, v in enumerate(vectors["invalid"]):
        L += byte_array(f"bad_vector_{i}_cbor", v["cbor"])
    L += ["", "static const protocol_vector_t protocol_vectors[] = {"]
    for i, v in enumerate(vectors["valid"]):
        ev = v["event"]
        type_name = ev["type"]
        default_prio = s["events"].get(type_name, {}).get("prio", "normal")
        prio = f"ATALAIA_PRIO_{c_ident(ev.get('prio', default_prio))}"
        # Field order of atalaia_event_t: node, seq, t_ms, team, squad, prio, type.
        L += [f"    {{{c_string(v['name'])},",
              f"     {{{ev['node']}, {ev['seq']}, {ev['t']}u, {ev.get('team', 0)}, {ev.get('squad', 0)}, "
              f"{prio}, {c_string(type_name)}}},",
              f"     {c_string(data_json(ev.get('data', {})))},",
              f"     vector_{i}_cbor, sizeof(vector_{i}_cbor)}},"]
    L += ["};", "", "static const protocol_bad_vector_t protocol_bad_vectors[] = {"]
    for i, v in enumerate(vectors["invalid"]):
        L.append(f"    {{{c_string(v['name'])}, bad_vector_{i}_cbor, sizeof(bad_vector_{i}_cbor)}},")
    L += ["};", "", "#endif /* ATALAIA_PROTOCOL_VECTORS_H */", ""]
    return "\n".join(L)


