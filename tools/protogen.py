FIELD_FRAME_VECTORS = REPO / "protocol" / "vectors" / "field_frame.json"
FF_KINDS = {"announce": "ATALAIA_FF_ANNOUNCE", "discover": "ATALAIA_FF_DISCOVER", "invite": "ATALAIA_FF_INVITE"}
FF_RESULTS = ("accepted", "busy", "refused", "no_mode", "not_box", "storage", "radio", "ended")


def gen_field_frame_vectors(fv: dict[str, Any]) -> str:
    """core/tests/field_frame_vectors.h: HKDF and field frame vectors for the C tests."""
    L = c_spdx("Field frame test vectors (protocol/vectors/field_frame.json).")
    L[5] = " * Generated by tools/protogen.py from protocol/vectors/field_frame.json. Do not edit."
    L += ["#ifndef ATALAIA_FIELD_FRAME_VECTORS_H", "#define ATALAIA_FIELD_FRAME_VECTORS_H", "",
          "#include <stdbool.h>", "#include <stddef.h>", "#include <stdint.h>", "",
          "#include \"atalaia/field_frame.h\"", ""]

    def arr(name: str, hexstr: str) -> list[str]:
        data = bytes.fromhex(hexstr)
        if not data:
            return [f"#define {name} ((const uint8_t *)\"\")", f"#define {name}_len 0"]
        out = [f"static const uint8_t {name}[] = {{"]
        for i in range(0, len(data), 12):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
        return out + ["};", f"#define {name}_len sizeof({name})"]

    def braces(hexstr: str) -> str:
        return "{" + ", ".join(f"0x{b:02x}" for b in bytes.fromhex(hexstr)) + "}"

    for i, v in enumerate(fv["hkdf_sha256"]):
        for part in ("ikm", "salt", "info", "prk", "okm"):
            L += arr(f"ff_hkdf_{i}_{part}", v[part])
    L += ["", "typedef struct {", "    const char *name;", "    const uint8_t *ikm;", "    size_t ikm_len;",
          "    const uint8_t *salt;", "    size_t salt_len;", "    const uint8_t *info;", "    size_t info_len;",
          "    const uint8_t *prk;", "    const uint8_t *okm;", "    size_t okm_len;", "} ff_hkdf_vector_t;", "",
          "static const ff_hkdf_vector_t ff_hkdf_vectors[] = {"]
    for i, v in enumerate(fv["hkdf_sha256"]):
        require(len(bytes.fromhex(v["okm"])) == v["length"], f"field_frame.json {v['name']}: okm length")
        n = f"ff_hkdf_{i}"
        L.append(f"    {{{c_string(v['name'])}, {n}_ikm, {n}_ikm_len, {n}_salt, {n}_salt_len, {n}_info, "
                 f"{n}_info_len, {n}_prk, {n}_okm, {n}_okm_len}},")
    L += ["};", "#define FF_HKDF_VECTOR_COUNT (sizeof(ff_hkdf_vectors) / sizeof(ff_hkdf_vectors[0]))", ""]

    L += arr("ff_join_key", fv["join_key"]) + arr("ff_field_key", fv["field_key"]) + [""]
    for i, v in enumerate(fv["valid"]):
        L += arr(f"ff_valid_{i}_body", v["body"]) + arr(f"ff_valid_{i}_nonce", v["nonce"])
        L += arr(f"ff_valid_{i}_frame", v["frame"])
    L += ["", "typedef struct {", "    const char *name;", "    atalaia_ff_msg_t fields;", "    const uint8_t *body;",
          "    size_t body_len;", "    const uint8_t *nonce;", "    const uint8_t *frame;", "    size_t frame_len;",
          "} ff_valid_vector_t;", "", "static const ff_valid_vector_t ff_valid_vectors[] = {"]
    for i, v in enumerate(fv["valid"]):
        f = v["fields"]
        init = [f".kind = {FF_KINDS[f['kind']]}"]
        if f["kind"] == "announce":
            init.append(".battery_pct = " + str(f.get("battery_pct", 255)))
        for key in ("device_id", "token"):
            if key in f:
                init.append(f".{key} = {braces(f[key])}")
        for key in ("name", "last_role"):
            if key in f:
                init.append(f".{key} = {c_string(f[key])}")
        for key in ("tier", "last_game", "answer", "invite_id", "part", "parts"):
            if key in f:
                init.append(f".{key} = {f[key]}")
        if "result" in f:
            init.append(f".result = {FF_RESULTS.index(f['result'])}")
        if "chunk" in f:
            init.append(f".chunk_len = {len(bytes.fromhex(f['chunk']))}")
            init.append(f".chunk = {braces(f['chunk'])}")
        L.append(f"    {{{c_string(v['name'])}, {{{', '.join(init)}}}, ff_valid_{i}_body, ff_valid_{i}_body_len, "
                 f"ff_valid_{i}_nonce, ff_valid_{i}_frame, ff_valid_{i}_frame_len}},")
    L += ["};", "#define FF_VALID_VECTOR_COUNT (sizeof(ff_valid_vectors) / sizeof(ff_valid_vectors[0]))", ""]

    L += arr("ff_hop_limit_ignored", fv["hop_limit_ignored"]) + [""]
    for i, v in enumerate(fv["invalid_frames"]):
        L += arr(f"ff_bad_frame_{i}", v["frame"])
    L += ["", "typedef struct {", "    const char *name;", "    const uint8_t *data;", "    size_t len;",
          "    const char *reason;", "} ff_bad_vector_t;", "", "static const ff_bad_vector_t ff_bad_frames[] = {"]
    for i, v in enumerate(fv["invalid_frames"]):
        L.append(f"    {{{c_string(v['name'])}, ff_bad_frame_{i}, ff_bad_frame_{i}_len, {c_string(v['reason'])}}},")
    L += ["};", "#define FF_BAD_FRAME_COUNT (sizeof(ff_bad_frames) / sizeof(ff_bad_frames[0]))", ""]
    for i, v in enumerate(fv["invalid_bodies"]):
        L += arr(f"ff_bad_body_{i}", v["body"])
    L += ["", "static const ff_bad_vector_t ff_bad_bodies[] = {"]
    for i, v in enumerate(fv["invalid_bodies"]):
        L.append(f"    {{{c_string(v['name'])}, ff_bad_body_{i}, ff_bad_body_{i}_len, \"body\"}},")
    L += ["};", "#define FF_BAD_BODY_COUNT (sizeof(ff_bad_bodies) / sizeof(ff_bad_bodies[0]))", ""]
    L += arr("ff_optional_key_skipped", fv["optional_key_skipped"]) + [""]

    for i, v in enumerate(fv["split"]):
        require(1 <= len(v["parts"]) <= 3, f"field_frame.json split {v['name']}: 1-3 parts")
        L += arr(f"ff_split_{i}_payload", v["payload"])
        for k, part in enumerate(v["parts"]):
            L += arr(f"ff_split_{i}_part_{k}", part)
    L += ["", "typedef struct {", "    const char *name;", "    const uint8_t *payload;", "    size_t payload_len;",
          "    size_t parts;", "    const uint8_t *part[3];", "    size_t part_len[3];", "} ff_split_vector_t;", "",
          "static const ff_split_vector_t ff_split_vectors[] = {"]
    for i, v in enumerate(fv["split"]):
        n = len(v["parts"])
        ptrs = ", ".join(f"ff_split_{i}_part_{k}" if k < n else "NULL" for k in range(3))
        lens = ", ".join(f"ff_split_{i}_part_{k}_len" if k < n else "0" for k in range(3))
        L.append(f"    {{{c_string(v['name'])}, ff_split_{i}_payload, ff_split_{i}_payload_len, {n}, {{{ptrs}}}, "
                 f"{{{lens}}}}},")
    L += ["};", "#define FF_SPLIT_VECTOR_COUNT (sizeof(ff_split_vectors) / sizeof(ff_split_vectors[0]))", ""]

    nv = fv["nonces"]
    L += arr("ff_nonce_key", nv["nonce_key"]) + [""]
    L += ["typedef struct {", "    const char *name;", "    uint8_t sender[8];", "    uint32_t boot;",
          "    uint16_t ctr;", "    uint8_t nonce[13];", "} ff_nonce_vector_t;", "",
          "static const ff_nonce_vector_t ff_nonce_vectors[] = {"]
    for v in nv["cases"]:
        L.append(f"    {{{c_string(v['name'])}, {braces(v['sender'])}, {v['boot']}u, {v['ctr']}u, "
                 f"{braces(v['nonce'])}}},")
    L += ["};", "#define FF_NONCE_VECTOR_COUNT (sizeof(ff_nonce_vectors) / sizeof(ff_nonce_vectors[0]))", ""]
    src = nv["source"]
    require(len(src["nonces"]) == 4, "field_frame.json nonces.source: four nonces")
    L += [f"static const uint8_t ff_nonce_source_sender[8] = {braces(src['sender'])};",
          f"#define FF_NONCE_SOURCE_STORED {src['stored_boot']}u",
          f"#define FF_NONCE_SOURCE_AFTER {src['stored_after']}u",
          "static const uint8_t ff_nonce_source[4][13] = {"]
    L += [f"    {braces(n)}," for n in src["nonces"]]
    L += ["};", "", "#endif /* ATALAIA_FIELD_FRAME_VECTORS_H */", ""]
    return "\n".join(L)


