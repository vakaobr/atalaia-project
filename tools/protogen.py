def gen_python(s: dict[str, Any]) -> str:
    def lit(v: Any) -> str:
        return repr(v)

    L = [*[f"# {line}" for line in SPDX_LINES],
         f'"""Skirmesh-RF protocol tables. {GENERATED}"""',
         "",
         "from __future__ import annotations",
         "",
         "from typing import NamedTuple, Optional",
         "",
         "",
         "class DataField(NamedTuple):",
         "    key: int",
         "    type: str  # string, integer, number or boolean",
         "    common: bool  # allowed in every event",
         "",
         "",
         "class EventDef(NamedTuple):",
         "    id: int",
         "    prio: str  # default priority",
         "    data: tuple[str, ...]  # data fields besides the common ones",
         "",
         "",
         "class PayloadField(NamedTuple):",
         "    key: int",
         "    type: str",
         "    required: bool",
         "    max: Optional[int] = None  # longest text or bytes, in bytes",
         "",
         "",
         f"PROTOCOL_VERSION = {s['version']}",
         f"RF_HEADER_BYTES = {s['header_bytes']}",
         f"RF_PAYLOAD_MAX = {s['payload_max']}",
         f"RF_MIC_BYTES = {s['mic_bytes']}",
         "",
         "# (name, offset, bytes)",
         "RF_HEADER = ("]
    L += [f"    ({lit(f['name'])}, {f['offset']}, {f['bytes']})," for f in s["header"]]
    L += [")", "", "MESSAGE_TYPES = {"]
    L += [f"    {lit(m['name'])}: {m['id']}," for m in s["messages"]]
    L += ["}", "",
          "# Longest event type name plus one, as in C.",
          f"EVENT_TYPE_MAX = {s['type_max'] + 1}",
          "# Custom events: x.<club>.<name>.",
          f"CUSTOM_EVENT_PATTERN = {CUSTOM_PATTERN!r}",
          "", "PRIORITIES = {"]
    L += [f"    {lit(k)}: {v['value']}," for k, v in s["prios"].items()]
    L += ["}", "", "ENVELOPE_KEYS = {"]
    L += [f"    {lit(k)}: {v['key']}," for k, v in s["envelope"].items()]
    L += ["}", "", "DATA_FIELDS = {"]
    L += [f"    {lit(k)}: DataField({v['key']}, {lit(v['type'])}, {bool(v.get('common'))}),"
          for k, v in s["fields"].items()]
    L += ["}", "", "EVENTS = {"]
    L += [f"    {lit(k)}: EventDef({v['id']}, {lit(v['prio'])}, {tuple(v.get('data', []))!r}),"
          for k, v in s["events"].items()]
    L += ["}", ""]
    if s.get("payloads"):
        L += ["PAYLOAD_FIELDS = {"]
        for msg_name, pfields in s["payloads"].items():
            L.append(f"    {lit(msg_name)}: {{")
            for f in pfields:
                extra = f", {f['max']}" if f.get("max") is not None else ""
                L.append(f"        {lit(f['name'])}: PayloadField({f['key']}, {lit(f['type'])}, {f['required']}{extra}),")
            L.append("    },")
        L += ["}", ""]
    return "\n".join(L)


# ---- JSON Schema -----------------------------------------------------------


def gen_json_schema(s: dict[str, Any]) -> str:
    json_types = {"string": {"type": "string"}, "integer": {"type": "integer"},
                  "number": {"type": "number"}, "boolean": {"type": "boolean"}}
    fields = s["fields"]
    common = [k for k, v in fields.items() if v.get("common")]
    defs: dict[str, Any] = {
        k: {**json_types[v["type"]], "description": v["doc"]} for k, v in fields.items()
    }

    def data_schema(names: list[str]) -> dict[str, Any]:
        return {"type": "object",
                "properties": {n: {"$ref": f"#/$defs/data/{n}"} for n in common + names},
                "additionalProperties": False}

    per_type = [
        {"if": {"properties": {"type": {"const": name}}},
         "then": {"properties": {"data": data_schema(e.get("data", []))}}}
        for name, e in s["events"].items()
    ]
    doc = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": GENERATED,
        "title": "Atalaia event",
        "description": "One event in the game log and on the API (design spec, section 8). "
                       "On the field, nodes use short numeric ids; the field controller "
                       "turns them into the names used here.",
        "type": "object",
        "required": ["id", "t", "node", "type", "prio"],
        "properties": {
            "id": {"type": "string", "pattern": "^.+:[0-9]+$",
                   "description": "node id and per-node sequence number"},
            "t": {"type": "integer", "minimum": 0, "maximum": 4294967295,
                  "description": s["envelope"]["t"]["doc"]},
            "node": {"type": "string", "minLength": 1, "description": "node id"},
            "type": {"anyOf": [{"enum": list(s["events"])},
                               {"type": "string", "pattern": CUSTOM_PATTERN,
                                "maxLength": s["type_max"]}],
                     "description": "standard event, or a custom one named x.<club>.<name>"},
            "team": {"type": "string", "description": "team name"},
            "squad": {"type": "string", "description": "squad name"},
            "prio": {"enum": list(s["prios"])},
            "data": {"type": "object", "default": {}},
        },
        "additionalProperties": False,
        "allOf": per_type,
        "$defs": {"data": defs},
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


