"""Generates the protocol tables from protocol/schema/*.yaml.

    python3 tools/protogen.py           write the generated files
    python3 tools/protogen.py --check   fail if any generated file is stale

Outputs, each marked "do not edit":

    core/include/atalaia/protocol.h     C constants, ids, keys and table types
    core/src/protocol.c                 C tables and lookups
    core/tests/protocol_vectors.h       codec test vectors for the C tests
    simulator/atalaia_sim/protocol.py   the same tables for Python
    protocol/json/event.schema.json     JSON Schema of an event in the game log

The codecs that use these tables are written by hand: core/src/codec.c and
simulator/atalaia_sim/codec.py. Both are tested against
protocol/vectors/events.yaml. Needs only PyYAML.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parents[1]
SCHEMA = REPO / "protocol" / "schema"
VECTORS = REPO / "protocol" / "vectors" / "events.yaml"

GENERATED = "Generated by tools/protogen.py from protocol/schema/. Do not edit."
# The licence header of every generated file.
# REUSE-IgnoreStart
SPDX_LINES = ("SPDX-FileCopyrightText: 2026 The Atalaia contributors",
              "SPDX-License-Identifier: GPL-3.0-or-later")
# REUSE-IgnoreEnd
FIELD_TYPES = ("string", "integer", "number", "boolean")
PAYLOAD_FIELD_TYPES = (
    "uint8", "uint16", "uint32", "int8", "text", "bytes",
    "array_uint8", "array_text", "map_u8_u32", "map_u16_u16", "map",
)
STANDARD_NAME = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$")
FIELD_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
MESSAGE_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")
# Custom events: x.<club>.<name>, for example x.myclub.power_plant.upgraded.
CUSTOM_PATTERN = r"^x\.[a-z0-9][a-z0-9_-]*(\.[a-z0-9][a-z0-9_-]*)+$"


class SchemaError(Exception):
    pass


def require(cond: bool, message: str) -> None:
    if not cond:
        raise SchemaError(message)


def load_yaml(path: Path) -> Any:
    with path.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


# ---- loading and validation ------------------------------------------------


def unique_ints(entries: dict[str, int], what: str, lo: int, hi: int) -> None:
    seen: dict[int, str] = {}
    for name, value in entries.items():
        require(isinstance(value, int) and not isinstance(value, bool) and lo <= value <= hi,
                f"{what} {name}: must be an integer from {lo} to {hi}")
        require(value not in seen, f"{what} {name}: {value} is already used by {seen.get(value)}")
        seen[value] = name


def load_schema() -> dict[str, Any]:
    msgs = load_yaml(SCHEMA / "messages.yaml")
    evs = load_yaml(SCHEMA / "events.yaml")
    require(msgs.get("version") == evs.get("version"),
            "messages.yaml and events.yaml must have the same version")

    header = []
    offset = 0
    for field in msgs["header"]:
        require(field["bytes"] in (1, 2, 4), f"header field {field['name']}: bytes must be 1, 2 or 4")
        header.append({"name": field["name"], "offset": offset, "bytes": field["bytes"],
                       "doc": field.get("doc", "")})
        offset += field["bytes"]

    messages = msgs["messages"]
    for m in messages:
        require(MESSAGE_NAME.match(m["name"]) is not None, f"message {m['name']}: names are UPPER_CASE")
    unique_ints({m["name"]: m["id"] for m in messages}, "message", 1, 255)

    type_max = evs["type_max_length"]
    require(isinstance(type_max, int) and 8 <= type_max <= 255, "type_max_length: 8 to 255")

    prios = evs["priorities"]
    unique_ints({k: v["value"] for k, v in prios.items()}, "priority", 0, 3)

    envelope = evs["envelope"]
    require(list(envelope) == ["node", "seq", "t", "type", "team", "squad", "prio", "data"],
            "envelope: the C and Python codecs expect node, seq, t, type, team, squad, prio, data")
    unique_ints({k: v["key"] for k, v in envelope.items()}, "envelope field", 1, 23)

    fields = evs["data_fields"]
    for name, f in fields.items():
        require(FIELD_NAME.match(name) is not None, f"data field {name}: names are lower_snake_case")
        require(f.get("type") in FIELD_TYPES, f"data field {name}: type is one of {', '.join(FIELD_TYPES)}")
    unique_ints({k: v["key"] for k, v in fields.items()}, "data field", 1, 255)

    events = evs["events"]
    for name, e in events.items():
        require(STANDARD_NAME.match(name) is not None and not name.startswith("x."),
                f"event {name}: standard names look like area.what and never start with x.")
        require(len(name) <= type_max, f"event {name}: longer than {type_max} bytes")
        require(e.get("prio") in prios, f"event {name}: unknown priority {e.get('prio')!r}")
        data = e.get("data", [])
        require(len(set(data)) == len(data), f"event {name}: data lists a field twice")
        for d in data:
            require(d in fields, f"event {name}: data field {d!r} is not in data_fields")
            require(not fields[d].get("common"), f"event {name}: {d!r} is common to every event; do not list it")
    unique_ints({k: v["id"] for k, v in events.items()}, "event", 1, 255)

    # ---- payload field definitions ----
    msg_names = {m["name"] for m in messages}
    payloads: dict[str, list[dict[str, Any]]] = {}
    raw_payloads = msgs.get("payloads", {})
    for msg_name, fields_list in raw_payloads.items():
        require(msg_name in msg_names, f"payload {msg_name}: not a known message type")
        seen_keys: dict[int, str] = {}
        seen_names: set[str] = set()
        validated: list[dict[str, Any]] = []
        for f in fields_list:
            fname = f["name"]
            fkey = f["key"]
            require(FIELD_NAME.match(fname) is not None,
                    f"payload {msg_name}.{fname}: names are lower_snake_case")
            require(fname not in seen_names,
                    f"payload {msg_name}.{fname}: duplicate field name")
            require(isinstance(fkey, int) and not isinstance(fkey, bool) and 1 <= fkey <= 23,
                    f"payload {msg_name}.{fname}: key must be 1-23")
            require(fkey not in seen_keys,
                    f"payload {msg_name}.{fname}: key {fkey} already used by {seen_keys.get(fkey)}")
            require(f.get("type") in PAYLOAD_FIELD_TYPES,
                    f"payload {msg_name}.{fname}: type must be one of {', '.join(PAYLOAD_FIELD_TYPES)}")
            require(isinstance(f.get("required"), bool),
                    f"payload {msg_name}.{fname}: required must be true or false")
            fmax = f.get("max")
            require(fmax is None or (isinstance(fmax, int) and not isinstance(fmax, bool) and fmax > 0),
                    f"payload {msg_name}.{fname}: max must be a positive integer")
            seen_keys[fkey] = fname
            seen_names.add(fname)
            validated.append({"key": fkey, "name": fname, "type": f["type"],
                              "required": f["required"], "max": fmax, "doc": f.get("doc", "")})
        payloads[msg_name] = validated

    return {
        "version": msgs["version"],
        "protocol": msgs["protocol"],
        "header": header,
        "header_bytes": offset,
        "payload_max": msgs["payload_max_bytes"],
        "mic_bytes": msgs["mic_bytes"],
        "messages": messages,
        "payloads": payloads,
        "type_max": type_max,
        "prios": prios,
        "envelope": envelope,
        "fields": fields,
        "events": events,
    }


def load_vectors(schema: dict[str, Any]) -> dict[str, Any]:
    vectors = load_yaml(VECTORS)
    require(bool(vectors["valid"]) and bool(vectors["invalid"]), "vectors: need valid and invalid cases")
    for v in vectors["valid"] + vectors["invalid"]:
        require(isinstance(v.get("cbor"), str), f"vector {v.get('name')!r}: cbor must be a quoted hex string")
    for v in vectors["valid"]:
        ev = v["event"]
        for key in ("node", "seq", "t", "type"):
            require(key in ev, f"vector {v['name']!r}: event needs {key}")
        require(set(ev) <= set(schema["envelope"]), f"vector {v['name']!r}: unknown envelope field")
        bytes.fromhex(v["cbor"])
    for v in vectors["invalid"]:
        bytes.fromhex(v["cbor"])
    return vectors


# ---- helpers ---------------------------------------------------------------


def c_ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def c_string(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def c_comment(s: str) -> str:
    return s.replace("*/", "* /")


def c_spdx(summary: str) -> list[str]:
    return [
        "/*",
        *[f" * {line}" for line in SPDX_LINES],
        " *",
        f" * {summary}",
        f" * {GENERATED}",
        " */",
        "/* clang-format off */",
    ]


def aligned(rows: list[tuple[str, str]], indent: str = "    ") -> list[str]:
    width = max(len(a) for a, _ in rows)
    return [f"{indent}{a.ljust(width)} {b}".rstrip() for a, b in rows]


def data_json(data: dict[str, Any]) -> str:
    return json.dumps(data, separators=(",", ":"), ensure_ascii=False)


