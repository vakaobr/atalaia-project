"""Builds the site server's breached-password file: hashes, not the passwords.

    python tools/breached_hashes.py                 download the pinned list and write the file
    python tools/breached_hashes.py --source FILE   use a local copy of it (checked the same way)

The source is the UK NCSC's list of the 100,000 passwords seen most often in
breaches (from Have I Been Pwned), as published in SecLists at a pinned
commit, under SecLists' MIT licence (decision S11-4). The server refuses
only entries of MIN_LENGTH characters or more (shorter ones fail the length
rule anyway), so only those are kept: each one NFKC-normalised and
lower-cased, then SHA-256 with a fixed prefix, truncated to 16 bytes, as hex,
sorted. The repository carries no readable list of leaked passwords
(maintainer's request, 2026-10-21); the hashes do not make them secret (anyone
can hash the public list), they only keep them out of sight.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
import unicodedata
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "server" / "atalaia_server" / "data" / "breached-passwords.sha256"

COMMIT = "1a7bb9127eca9e6ff2fc0301c597fe6e16a0cb56"
PATH = "Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt"
URL = f"https://raw.githubusercontent.com/danielmiessler/SecLists/{COMMIT}/{PATH}"
SOURCE_SHA256 = "c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0"

MIN_LENGTH = 10            # server/atalaia_server/passwords.py's MIN_LENGTH
PREFIX = b"atalaia-breached-v1\x00"
DIGEST_BYTES = 16


def entry_hash(password: str) -> str:
    """The hash of one password as the server computes it (passwords.breached_hash)."""
    text = unicodedata.normalize("NFKC", password).lower()
    return hashlib.sha256(PREFIX + text.encode("utf-8")).digest()[:DIGEST_BYTES].hex()


def build(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise SystemExit("breached_hashes: the source is not the pinned list (SHA-256 differs)")
    words = source.decode("utf-8").splitlines()
    kept = {entry_hash(w) for w in words if len(unicodedata.normalize("NFKC", w)) >= MIN_LENGTH}
    # The generated file's own tags, not this script's:
    # REUSE-IgnoreStart
    header = [
        "# SPDX-FileCopyrightText: 2018 Daniel Miessler and the SecLists contributors",
        "# SPDX-License-Identifier: MIT",
        "#",
        "# Generated by tools/breached_hashes.py: do not edit. The site server's breached-password",
        "# list (decision S11-4) as hashes: SecLists' " + PATH,
        f"# at commit {COMMIT} (SHA-256 {SOURCE_SHA256}),",
        f"# entries of {MIN_LENGTH}+ characters, NFKC and lower-cased, SHA-256 of",
        "# 'atalaia-breached-v1\\0' + the entry, first 16 bytes as hex, sorted.",
        f"# {len(kept)} entries.",
    ]
    # REUSE-IgnoreEnd
    return "\n".join(header + sorted(kept)) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, help="a local copy of the pinned list")
    args = parser.parse_args(argv)
    if args.source:
        source = args.source.read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=60) as response:  # noqa: S310 (a pinned https URL)
            source = response.read()
    OUT.write_text(build(source), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
