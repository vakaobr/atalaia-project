"""Writes core/scenario/unicode.lua, the Unicode classes the scenario compiler needs (PE24-109).

    python3 tools/scenario_unicode.py           write the file
    python3 tools/scenario_unicode.py --check   fail if it is stale

The compiler (core/scenario/, one implementation for the Pi and the phone) asks three things of a
character, which its rules were first written with Python's unicodedata for:

* printable (general category L, M, N, P or S): written as it is in field.lua's strings, and in
  repr()'s quotes in a problem's message (str.isprintable, with the space);
* a control (Cc, Cf, Zl or Zp): not allowed in a one-line text such as a name;
* whitespace (str.isspace): what str.strip() removes, for "a non-empty text".

Everything else (Zs, Co, Cn, Cs) is neither. The table is generated from this Python's
unicodedata; ``--check`` compares only when the Python running it has the table's Unicode
version (the dev container's Python 3.12 has 15.0.0), since another version is not stale data
but a different one.
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "core" / "scenario" / "unicode.lua"


def klass(cp: int) -> str:
    cat = unicodedata.category(chr(cp))
    if cat[0] in "LMNPS":
        return "P"
    if cat in ("Cc", "Cf", "Zl", "Zp"):
        return "C"
    return "O"


def generate() -> str:
    starts: list[int] = []
    classes: list[str] = []
    for cp in range(0x110000):
        k = klass(cp)
        if not classes or classes[-1] != k:
            starts.append(cp)
            classes.append(k)
    spaces = [cp for cp in range(0x110000) if chr(cp).isspace()]
    lines = []
    row: list[str] = []
    for s in starts:
        row.append(f"0x{s:X}")
        if len(row) == 10:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    class_lines = ["  " + repr("".join(classes[i:i + 90])).replace("'", '"') for i in range(0, len(classes), 90)]
    return (
        "-- SPDX-" "FileCopyrightText: 2026 The Atalaia contributors\n"
        "-- SPDX-" "License-Identifier: GPL-3.0-or-later\n"
        "--\n"
        "-- Generated by tools/scenario_unicode.py from Python's unicodedata "
        f"{unicodedata.unidata_version}: do not edit.\n"
        "-- class(c): \"P\" printable (L, M, N, P, S), \"C\" a control (Cc, Cf, Zl, Zp), \"O\" other\n"
        "-- (Zs, Co, Cn, Cs); space(c): Python's str.isspace.\n"
        "local M = {}\n"
        f'M.version = "{unicodedata.unidata_version}"\n'
        "\n"
        "-- The first code point of each run of one class.\n"
        "local STARTS = {\n" + "\n".join(lines) + "\n}\n"
        "-- The class of each run.\n"
        "local CLASSES = table.concat({\n" + ",\n".join(class_lines) + ",\n})\n"
        "local SPACES = {}\n"
        "for _, c in ipairs({ " + ", ".join(f"0x{c:X}" for c in spaces) + " }) do\n"
        "  SPACES[c] = true\n"
        "end\n"
        "\n"
        "function M.class(c)\n"
        "  local lo, hi = 1, #STARTS\n"
        "  while lo < hi do\n"
        "    local mid = (lo + hi + 1) // 2\n"
        "    if STARTS[mid] <= c then\n"
        "      lo = mid\n"
        "    else\n"
        "      hi = mid - 1\n"
        "    end\n"
        "  end\n"
        "  return string.sub(CLASSES, lo, lo)\n"
        "end\n"
        "\n"
        "function M.space(c)\n"
        "  return SPACES[c] == true\n"
        "end\n"
        "\n"
        "return M\n"
    )


def file_version(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("M.version = "):
            return line.split('"')[1]
    return ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = ap.parse_args()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current and file_version(current) != unicodedata.unidata_version:
            print(f"scenario_unicode.py: {OUT.relative_to(REPO)} is Unicode {file_version(current)}, this Python "
                  f"has {unicodedata.unidata_version}: not compared (the dev container's Python generates it)")
            return 0
        if current != generate():
            print(f"{OUT.relative_to(REPO)} is stale: run python3 tools/scenario_unicode.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} (Unicode {unicodedata.unidata_version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
