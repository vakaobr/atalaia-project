"""Generates the on-board OLED's boot splash logo from the site's favicon.

    python tools/oled_logo.py      writes firmware/esp32/main/oled_logo.c

The tower and flame of site/favicon.svg (a 32x32 viewBox), drawn as
polygons (the flame's curves flattened by hand), scaled to a 30x60 one-bit
image with 4x4 supersampling, stored as LVGL A8 (0x00 or 0xFF per pixel)
so the OLED view draws it like any other image. Plain Python, no Pillow.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "firmware" / "esp32" / "main" / "oled_logo.c"

W, H = 30, 60
SCALE = 2.2           # favicon units -> pixels
ORIGIN = (9.0, 2.0)   # favicon point drawn at pixel (0, 0)
SUB = 4               # supersampling per axis

# Filled shapes (favicon.svg coordinates), then holes cut out of them.
FLAME = [(16, 2.5), (17.3, 4.0), (18.3, 5.6), (18.4, 7.0), (18, 8.1), (17.4, 8.8),
         (16.6, 8.8), (16, 8.5), (15.4, 8.8), (14.6, 8.8), (14, 8.1), (13.6, 7.0),
         (13.7, 5.6), (14.7, 4.0)]
BATTLEMENTS = [(10, 15.5), (10, 10), (13, 10), (13, 12.6), (14.6, 12.6), (14.6, 10),
               (17.4, 10), (17.4, 12.6), (19, 12.6), (19, 10), (22, 10), (22, 15.5)]
BODY = [(11, 15.5), (21, 15.5), (22.6, 28.5), (9.4, 28.5)]
DOOR = [(15, 28.5), (15, 24.2), (15.5, 23.4), (16, 23.2), (16.5, 23.4), (17, 24.2), (17, 28.5)]
WINDOW = [(15.4, 17.5), (16.6, 17.5), (16.6, 20), (15.4, 20)]

FILLED = [FLAME, BATTLEMENTS, BODY]
HOLES = [DOOR, WINDOW]


def inside(poly: list[tuple[float, float]], x: float, y: float) -> bool:
    """Even-odd point-in-polygon test."""
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def pixel(px: int, py: int) -> bool:
    covered = 0
    for sy in range(SUB):
        for sx in range(SUB):
            x = ORIGIN[0] + (px + (sx + 0.5) / SUB) / SCALE
            y = ORIGIN[1] + (py + (sy + 0.5) / SUB) / SCALE
            if any(inside(p, x, y) for p in FILLED) and not any(inside(p, x, y) for p in HOLES):
                covered += 1
    return covered * 2 >= SUB * SUB


def main() -> int:
    rows = []
    for py in range(H):
        rows.append(", ".join("0xFF" if pixel(px, py) else "0x00" for px in range(W)))
    preview = "\n".join(
        " * " + "".join("#" if pixel(px, py) else "." for px in range(W)) for py in range(0, H, 2))
    OUT.write_text(f"""/*
 * SPDX-FileCopyrightText: 2026 The Atalaia contributors
 * SPDX-License-Identifier: CC-BY-SA-4.0
 *
 * Generated by tools/oled_logo.py from site/favicon.svg: do not edit.
 * The boot splash tower of the on-board OLED, {W}x{H}, LVGL A8. Every
 * other row:
{preview}
 */
#include "oled_logo.h"

const uint8_t oled_logo_a8[OLED_LOGO_W * OLED_LOGO_H] = {{
""" + "".join(f"    {r},\n" for r in rows) + "};\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
