"""Generates the on-board OLED's logos from the site's favicon.

    python tools/oled_logo.py      writes firmware/esp32/main/oled_logo.c (the modem's icon) and
                                   firmware/esp32/assets/splash.pgm (the default boot splash)

The tower and flame of site/favicon.svg (a 32x32 viewBox), drawn as
polygons (the flame's curves flattened by hand), scaled to one-bit images
with 4x4 supersampling, stored as LVGL A8 (0x00 or 0xFF per pixel) so the
OLED views draw them like any other image: the 30x60 boot splash tower and
a 9x14 icon for the USB radio modem's header bar. Plain Python, no Pillow.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "firmware" / "esp32" / "main" / "oled_logo.c"
# The boot splash is an asset the build embeds (main/splash_logo.cmake; a builder points
# CONFIG_ATALAIA_SPLASH_LOGO at another file): a plain-text PGM, the Atalaia towers by default.
SPLASH = REPO / "firmware" / "esp32" / "assets" / "splash.pgm"

# C array, size macro prefix, width, height, favicon units -> pixels, and the
# favicon point drawn at pixel (0, 0).
IMAGES = [
    ("oled_logo_a8", "OLED_LOGO", 30, 60, 2.2, (9.0, 2.0)),
    ("oled_icon_a8", "OLED_ICON", 9, 14, 0.6, (8.6, 2.6)),
]
SUB = 4  # supersampling per axis

# Filled shapes (favicon.svg coordinates), then holes cut out of them.
FLAME = [(16, 2.5), (17.3, 4.0), (18.3, 5.6), (18.4, 7.0), (18, 8.1), (17.4, 8.8),
         (16.6, 8.8), (16, 8.5), (15.4, 8.8), (14.6, 8.8), (14, 8.1), (13.6, 7.0),
         (13.7, 5.6), (14.7, 4.0)]
BATTLEMENTS = [(10, 15.5), (10, 10), (13, 10), (13, 12.6), (14.6, 12.6), (14.6, 10),
               (17.4, 10), (17.4, 12.6), (19, 12.6), (19, 10), (22, 10), (22, 15.5)]
BODY = [(11, 15.5), (21, 15.5), (22.6, 28.5), (9.4, 28.5)]
DOOR = [(15, 28.5), (15, 24.2), (15.5, 23.4), (16, 23.2), (16.5, 23.4), (17, 24.2), (17, 28.5)]
WINDOW = [(15.4, 17.5), (16.6, 17.5), (16.6, 20), (15.4, 20)]

FILLED = [FLAME, BATTLEMENTS, BODY]
HOLES = [DOOR, WINDOW]


def inside(poly: list[tuple[float, float]], x: float, y: float) -> bool:
    """Even-odd point-in-polygon test."""
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def pixel(px: int, py: int, scale: float, origin: tuple[float, float]) -> bool:
    covered = 0
    for sy in range(SUB):
        for sx in range(SUB):
            x = origin[0] + (px + (sx + 0.5) / SUB) / scale
            y = origin[1] + (py + (sy + 0.5) / SUB) / scale
            if any(inside(p, x, y) for p in FILLED) and not any(inside(p, x, y) for p in HOLES):
                covered += 1
    return covered * 2 >= SUB * SUB


def image(name: str, macro: str, w: int, h: int, scale: float,
          origin: tuple[float, float]) -> tuple[str, str]:
    """The C array and its preview (every other row of a tall image)."""
    step = 2 if h > 30 else 1
    rows = [", ".join("0xFF" if pixel(px, py, scale, origin) else "0x00" for px in range(w))
            for py in range(h)]
    preview = "\n".join(
        " * " + "".join("#" if pixel(px, py, scale, origin) else "." for px in range(w))
        for py in range(0, h, step))
    array = (f"const uint8_t {name}[{macro}_W * {macro}_H] = {{\n"
             + "".join(f"    {r},\n" for r in rows) + "};\n")
    return array, preview


def main() -> int:
    arrays, previews = [], []
    for name, macro, w, h, scale, origin in IMAGES:
        if name == "oled_logo_a8":
            write_splash(w, h, scale, origin)
            continue
        array, preview = image(name, macro, w, h, scale, origin)
        arrays.append(array)
        rows = "every other row" if h > 30 else "every row"
        previews.append(f" * {name}, {w}x{h}, {rows}:\n{preview}\n")
    OUT.write_text("""/*
 * SPDX-FileCopyrightText: 2026 The Atalaia contributors
 * SPDX-License-Identifier: CC-BY-SA-4.0
 *
 * Generated by tools/oled_logo.py from site/favicon.svg: do not edit.
 * The USB radio modem's header icon, LVGL A8. (The boot splash tower, oled_logo_a8, is the asset
 * assets/splash.pgm, embedded by splash_logo.cmake.)
 *
""" + " *\n".join(previews) + """ */
#include "oled_logo.h"

""" + "\n".join(arrays), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


def write_splash(w: int, h: int, scale: float, origin: tuple[float, float]) -> None:
    """The default splash as a plain-text PGM (P2): 255 = lit, 0 = dark."""
    rows = [" ".join("255" if pixel(px, py, scale, origin) else "0" for px in range(w))
            for py in range(h)]
    SPLASH.parent.mkdir(parents=True, exist_ok=True)
    SPLASH.write_text(
        "P2\n# SPDX-FileCopyrightText: 2026 The Atalaia contributors\n# SPDX-License-Identifier: CC-BY-SA-4.0\n# The Atalaia towers, the Field Box's boot splash (30x60, one lit/dark value per pixel).\n"
        "# Generated by tools/oled_logo.py from site/favicon.svg; replace the file (or point\n"
        "# CONFIG_ATALAIA_SPLASH_LOGO at yours) to build a box with another splash. See\n"
        "# firmware/esp32/README.md, \"Your own splash logo\".\n"
        f"{w} {h}\n255\n" + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {SPLASH.relative_to(REPO)}")


if __name__ == "__main__":
    raise SystemExit(main())
