"""tools/release_package.py refuses a build whose boot splash is not the Atalaia tower (decision LOGO-7)."""

from __future__ import annotations

import importlib.util
import shutil
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("release_package", REPO / "tools" / "release_package.py")
tool = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tool)


class Splash(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        root = Path(self._tmp.name)
        self.repo = root / "repo"
        (self.repo / "firmware/esp32/assets").mkdir(parents=True)
        self.pgm = self.repo / "firmware/esp32" / tool.SPLASH_DEFAULT
        shutil.copy(REPO / "firmware/esp32" / tool.SPLASH_DEFAULT, self.pgm)
        self.build = root / "build"
        (self.build / "esp-idf/main").mkdir(parents=True)
        self.sdkconfig = self.build / "sdkconfig"
        self.sdkconfig.write_text('CONFIG_ATALAIA_SPLASH_LOGO="assets/splash.pgm"\n', encoding="utf-8")
        self.c = self.build / "esp-idf/main/splash_logo.c"
        self.write_c(tool.splash_bytes(self.pgm))

    def write_c(self, data: bytes) -> None:
        body = "".join("0x%02X,\n" % b for b in data)
        self.c.write_text(f"/* Generated by splash_logo.cmake from /x/0x11/splash.pgm. */\nconst uint8_t a[] = {{\n{body}}};\n",
                          encoding="utf-8")

    def test_committed_asset_is_the_pinned_tower(self) -> None:
        self.assertIsNone(tool.splash_problem(self.build, self.repo))

    def test_default_in_the_real_repo(self) -> None:
        self.assertEqual(tool.hashlib.sha256((REPO / "firmware/esp32" / tool.SPLASH_DEFAULT).read_bytes()).hexdigest(),
                         tool.SPLASH_SHA256)

    def test_sdkconfig_without_the_option_is_fine(self) -> None:
        self.sdkconfig.write_text("CONFIG_X=y\n", encoding="utf-8")
        self.assertIsNone(tool.splash_problem(self.build, self.repo))

    def test_another_asset_refused(self) -> None:
        self.pgm.write_text(self.pgm.read_text(encoding="utf-8") + "\n# edited\n", encoding="utf-8")
        self.assertIn("not the project's Atalaia tower", tool.splash_problem(self.build, self.repo))

    def test_other_kconfig_path_refused(self) -> None:
        self.sdkconfig.write_text('CONFIG_ATALAIA_SPLASH_LOGO="/home/me/mine.pgm"\n', encoding="utf-8")
        self.assertIn("mine.pgm", tool.splash_problem(self.build, self.repo))

    def test_embedded_array_of_another_image_refused(self) -> None:
        data = bytearray(tool.splash_bytes(self.pgm))
        data[0] ^= 0xFF
        self.write_c(bytes(data))
        self.assertIn("another splash", tool.splash_problem(self.build, self.repo))

    def test_an_io_pod_build_has_no_splash(self) -> None:
        self.sdkconfig.write_text("CONFIG_ATALAIA_POD_MODE=y\n", encoding="utf-8")
        self.c.unlink()
        self.assertIsNone(tool.splash_problem(self.build, self.repo))

    def test_an_io_pod_build_with_a_splash_is_refused(self) -> None:
        self.sdkconfig.write_text("CONFIG_ATALAIA_POD_MODE=y\n", encoding="utf-8")
        self.assertIn("should embed none", tool.splash_problem(self.build, self.repo))

    def test_missing_pieces_refused(self) -> None:
        self.c.unlink()
        self.assertIn("splash_logo.c", tool.splash_problem(self.build, self.repo))
        self.sdkconfig.unlink()
        self.assertIn("sdkconfig", tool.splash_problem(self.build, self.repo))


class ReleaseNotesGuides(unittest.TestCase):
    def test_every_guide_the_notes_link_exists(self) -> None:
        source = (REPO / "tools" / "release_package.py").read_text(encoding="utf-8")
        import re
        guides = re.findall(r"\{args\.tag\}/(docs/manuals/en/[a-z-]+\.md)", source)
        self.assertIn("docs/manuals/en/modem.md", guides)
        for guide in guides:
            self.assertTrue((REPO / guide).is_file(), guide)

    def test_the_apk_fingerprint_is_the_workflows_and_the_keys_page(self) -> None:
        # One certificate everywhere (decisions APK-1 to APK-8): the notes, release.yml's check
        # and the page users verify against must not drift apart.
        import re
        source = (REPO / "tools" / "release_package.py").read_text(encoding="utf-8")
        fp = re.search(r'ANDROID_CERT_SHA256 = \("([0-9A-F:]{95})"\)', source).group(1)
        workflow = (REPO / ".github" / "workflows" / "release.yml").read_text(encoding="utf-8")
        self.assertIn(f"ANDROID_CERT_SHA256: {fp}", workflow)
        self.assertIn(fp, (REPO / "docs" / "community" / "keys.md").read_text(encoding="utf-8"))
        self.assertIn("{ANDROID_CERT_SHA256}", source)
        for guide in re.findall(r"\{args\.tag\}/(docs/[a-z/-]+\.md)", source):
            self.assertTrue((REPO / guide).is_file(), guide)


if __name__ == "__main__":
    unittest.main()
