"""What only staff may read (decision M5-1): one rule for events and game parameters.

Some data is a secret of the game until a team earns it: the code a Hacking
Terminal reveals (``hacking.solved``'s ``code``), a Bomb's team codes, the
codes of the Codes modifier. The schema says which, so the rule needs no list
here:

- an event's data fields marked ``gm_only`` in ``protocol/schema/events.yaml``
  (``atalaia_sim.protocol.EVENTS[type].gm_only``, generated by protogen);
- a mode's parameters marked ``gm_only: true`` in its ``mode.yaml``
  (``Mode.gm_only_params``).

Staff (the GM token, and the marshal and gm player tokens of the game) get
everything. Everyone else (players, the read token's scoreboards and console)
gets the event and the game without those fields, on the stream (its hello,
``event`` and ``game`` messages), on REST (``/games``, ``/games/{id}``,
``/games/{id}/log``, the read token's ``/presets``) and on MQTT (whose topics
any scoreboard on the field's network may read). The radio, the controller's
own log and the sync to the site server (whose event pages and game
parameters are for staff only, protocol/sync.md) keep the whole event: the
boxes need the codes, and the GM needs the log.

Scenario objectives (decision P4R24, plan phase 8): which objective a
``scenario.objective.*`` event is about (its ``objective``, gm_only in the
schema since plan phase 6, M6-5) also reaches the players it is for, by the
objective's visibility in the scenario package's ``mode.yaml`` (M7-8):
``public`` to everyone, ``team`` to the assignee team's players, ``squad`` to
that team's squad, ``hidden`` to its assignee (squad, else team, else everyone)
once revealed; the scenario's runtime sends nothing about a hidden objective
before its reveal. Everyone else gets the event without ``objective``, as
before. ``objective_visible`` is that rule; ``scenario_event`` applies it.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Optional

from atalaia_sim.protocol import EVENTS

if TYPE_CHECKING:
    from atalaia_sim.mode import Mode

    from .checkin import Viewer

GM_ONLY_DATA: dict[str, frozenset[str]] = {name: frozenset(e.gm_only) for name, e in EVENTS.items() if e.gm_only}


def is_staff(viewer: Optional["Viewer"], game_id: Optional[int] = None) -> bool:
    """The GM token, or a marshal or gm player token (of this game, when one is named)."""
    if viewer is None or not viewer.is_staff:
        return False
    return viewer.kind != "player" or game_id is None or viewer.game_id == game_id


def public_event(ev: dict[str, Any]) -> dict[str, Any]:
    """An event (log record or stream form) without its gm_only data fields."""
    hidden = GM_ONLY_DATA.get(ev.get("type"))  # type: ignore[arg-type]
    data = ev.get("data")
    if not hidden or not isinstance(data, dict) or not hidden & data.keys():
        return ev
    return {**ev, "data": {k: v for k, v in data.items() if k not in hidden}}


OBJECTIVE_EVENTS = frozenset({"scenario.objective.completed", "scenario.objective.failed",
                              "scenario.objective.revealed"})


def _player_team(viewer: Optional["Viewer"], game: dict[str, Any]) -> Optional[str]:
    """A player token's team name in this game (None: not a player of it, or no team)."""
    if viewer is None or viewer.kind != "player" or viewer.game_id != game.get("id"):
        return None
    teams = game.get("teams") or []
    return teams[viewer.team - 1] if 1 <= viewer.team <= len(teams) else None


DISCLOSURES = ("members", "leader")
FULL, NOTICE, NONE = "full", "notice", "none"


def objective_access(viewer: Optional["Viewer"], objective: dict[str, Any], game: dict[str, Any],
                     disclosure: str = "members") -> str:
    """What a viewer gets of this objective (its id, names and state; P4R24, SQ-3): ``full``, ``notice``
    (a member of the squad whose leader alone is told: only that the leader has orders) or ``none``.
    A squad leader is told of the objectives of their own squad and of their whole team; so is a
    player who belongs to no squad, who has no leader to be told through.

    ``objective`` is one entry of a scenario package's ``scenario.objectives`` (M7-8): its
    ``visibility`` and its assignee's ``team`` and ``squad``. Whether a hidden one has been
    revealed yet is the caller's to know (the runtime never sends an event about it before).
    """
    if is_staff(viewer, game.get("id")):
        return FULL
    vis = objective.get("visibility", "public")
    team, squad = objective.get("team"), objective.get("squad")
    if vis == "hidden":
        vis = "squad" if squad is not None else "team" if team is not None else "public"
    if vis == "public" or team is None:
        return FULL
    if viewer is None or _player_team(viewer, game) != team:
        return NONE
    if vis == "squad" and squad is not None and str(viewer.squad) != str(squad):
        return NONE
    if disclosure == "leader" and viewer.squad != 0 and viewer.role != "squad_leader":
        return NOTICE
    return FULL


def objective_visible(viewer: Optional["Viewer"], objective: dict[str, Any], game: dict[str, Any],
                      disclosure: str = "members") -> bool:
    """Whether a viewer may know this objective whole (``objective_access`` is ``full``)."""
    return objective_access(viewer, objective, game, disclosure) == FULL


def scenario_event(viewer: Optional["Viewer"], ev: dict[str, Any], game: Optional[dict[str, Any]],
                   objectives: Optional[dict[str, dict[str, Any]]], disclosure: str = "members") -> dict[str, Any]:
    """An event as this viewer may see it: whole for staff and, for a scenario objective's event,
    for the players the objective is for (``objectives``: the game's scenario objectives by id);
    else without its gm_only data (``public_event``)."""
    if is_staff(viewer, game.get("id") if game is not None else None):
        return ev
    data = ev.get("data")
    if game is not None and objectives and ev.get("type") in OBJECTIVE_EVENTS and isinstance(data, dict):
        objective = objectives.get(data.get("objective"))  # type: ignore[arg-type]
        access = objective_access(viewer, objective, game, disclosure) if objective is not None else NONE
        if access == FULL:
            return ev
        if access == NOTICE and ev["type"] == "scenario.objective.revealed":
            # The squad's leader has orders (SQ-3): this member is told so, not which.
            return {**public_event(ev), "data": {**public_event(ev)["data"], "leader_only": True}}
    return public_event(ev)


def public_params(mode: Optional["Mode"], params: Any) -> dict[str, Any]:
    """A game's or preset's parameters without the gm_only ones. A mode the controller no
    longer knows hides every parameter: nothing says which of them are secret."""
    if not isinstance(params, dict):
        return {}
    if mode is None:
        return {}
    return mode.public_params(params)
