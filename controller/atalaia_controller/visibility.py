"""What only staff may read (decision M5-1): one rule for events and game parameters.

Some data is a secret of the game until a team earns it: the code a Hacking
Terminal reveals (``hacking.solved``'s ``code``), a Bomb's team codes, the
codes of the Codes modifier. The schema says which, so the rule needs no list
here:

- an event's data fields marked ``gm_only`` in ``protocol/schema/events.yaml``
  (``atalaia_sim.protocol.EVENTS[type].gm_only``, generated by protogen);
- a mode's parameters marked ``gm_only: true`` in its ``mode.yaml``
  (``Mode.gm_only_params``).

Staff (the GM token, and the marshal and gm player tokens of the game) get
everything. Everyone else (players, the read token's scoreboards and console)
gets the event and the game without those fields, on the stream (its hello,
``event`` and ``game`` messages), on REST (``/games``, ``/games/{id}``,
``/games/{id}/log``, the read token's ``/presets``) and on MQTT (whose topics
any scoreboard on the field's network may read). The radio, the controller's
own log and the sync to the site server (whose event pages and game
parameters are for staff only, protocol/sync.md) keep the whole event: the
boxes need the codes, and the GM needs the log.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Optional

from atalaia_sim.protocol import EVENTS

if TYPE_CHECKING:
    from atalaia_sim.mode import Mode

    from .checkin import Viewer

GM_ONLY_DATA: dict[str, frozenset[str]] = {name: frozenset(e.gm_only) for name, e in EVENTS.items() if e.gm_only}


def is_staff(viewer: Optional["Viewer"], game_id: Optional[int] = None) -> bool:
    """The GM token, or a marshal or gm player token (of this game, when one is named)."""
    if viewer is None or not viewer.is_staff:
        return False
    return viewer.kind != "player" or game_id is None or viewer.game_id == game_id


def public_event(ev: dict[str, Any]) -> dict[str, Any]:
    """An event (log record or stream form) without its gm_only data fields."""
    hidden = GM_ONLY_DATA.get(ev.get("type"))  # type: ignore[arg-type]
    data = ev.get("data")
    if not hidden or not isinstance(data, dict) or not hidden & data.keys():
        return ev
    return {**ev, "data": {k: v for k, v in data.items() if k not in hidden}}


def public_params(mode: Optional["Mode"], params: Any) -> dict[str, Any]:
    """A game's or preset's parameters without the gm_only ones. A mode the controller no
    longer knows hides every parameter: nothing says which of them are secret."""
    if not isinstance(params, dict):
        return {}
    if mode is None:
        return {}
    return mode.public_params(params)
