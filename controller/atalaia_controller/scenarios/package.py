"""The compiled scenario package (kind: scenario, decision P4R7): mode.yaml and field.lua.

mode.yaml carries what the controller and the app need to show the scenario without reading
its Lua: the names in English and Portuguese, the scenario's parameters, and under ``scenario``
the boxes' language, the teams, the squads, the nodes the GM assigns (P4R8) and every
objective's id, type, names, assignee, visibility, dependencies and points (for the per-team
routing and the player view of plan phase 8). Codes and destinations are only in field.lua,
which only staff read.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from . import manifest as m
from .lua import LICENSE, SPDX_TAG, field_lua




@dataclass
class Package:
    id: str
    version: str
    files: dict[str, str]  # mode.yaml and field.lua, as modes.parse_package takes them

    @property
    def mode_yaml(self) -> str:
        return self.files["mode.yaml"]

    @property
    def field_lua(self) -> str:
        return self.files["field.lua"]

    def write(self, folder: Path) -> list[Path]:
        """Writes the package's files into folder (made if needed); returns their paths."""
        folder.mkdir(parents=True, exist_ok=True)
        out = []
        for name, text in sorted(self.files.items()):
            path = folder / name
            path.write_text(text, encoding="utf-8")
            out.append(path)
        return out


def _texts(entry: dict[str, Any], keys: tuple[str, ...]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for lang, strings in (entry.get("i18n") or {}).items():
        picked = {k: strings[k] for k in keys if strings.get(k)}
        if picked:
            out[lang] = picked
    return out


def _objective_meta(o: dict[str, Any]) -> dict[str, Any]:
    assignee = o.get("assignee") or {}
    effect = o.get("effect") or {}
    meta: dict[str, Any] = {"id": o["id"], "type": o["type"], "name": o["name"]}
    if o.get("description"):
        meta["description"] = o["description"]
    texts = _texts(o, ("name", "description"))
    if texts:
        meta["i18n"] = texts
    if assignee.get("team") is not None:
        meta["team"] = assignee["team"]
    if assignee.get("squad") is not None:
        meta["squad"] = assignee["squad"]
    meta["visibility"] = o.get("visibility", m.default_visibility(o))
    if o.get("target") is not None:
        meta["target"] = o["target"]
    for key in ("depends_on",):
        if o.get(key):
            meta[key] = list(o[key])
    if effect.get("reveal"):
        meta["reveals"] = list(effect["reveal"])
    if effect.get("points") is not None:
        meta["points"] = effect["points"]
    if effect.get("win"):
        meta["win"] = True
    if o.get("time_window"):
        meta["time_window"] = dict(o["time_window"])
    return meta


def mode_yaml(manifest: dict[str, Any]) -> str:
    doc: dict[str, Any] = {
        "id": manifest["id"],
        "version": str(manifest["version"]),
        "license": LICENSE,
        "kind": "scenario",
        "name": manifest["name"],
    }
    if manifest.get("description"):
        doc["description"] = manifest["description"]
    if manifest.get("author"):
        doc["author"] = manifest["author"]
    if manifest.get("params"):
        doc["params"] = {name: dict(spec) for name, spec in manifest["params"].items()}
    texts = _texts(manifest, ("name", "description", "params"))
    if texts:
        doc["i18n"] = texts
    doc["scenario"] = {
        "lang": manifest.get("lang", "pt"),
        "teams": list(manifest.get("teams", ["red", "blue"])),
        "squads": manifest.get("squads", 0),
        "nodes": {name: dict(spec) for name, spec in (manifest.get("nodes") or {}).items()},
        "objectives": [_objective_meta(o) for o in manifest["objectives"]],
    }
    head = (f"# {SPDX_TAG} {LICENSE}\n"
            "#\n"
            "# Generated by the Atalaia scenario compiler (controller/atalaia_controller/scenarios) from a\n"
            "# scenario manifest: a scenario package (kind: scenario, decision P4R7) that leads the game's id,\n"
            f"# <this id>+{m.OBJECTIVES_PACKAGE}. Compile the manifest again rather than editing this file.\n")
    return head + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)


def build(manifest: dict[str, Any]) -> Package:
    """The package of a manifest that validated without errors."""
    return Package(manifest["id"], str(manifest["version"]),
                   {"mode.yaml": mode_yaml(manifest), "field.lua": field_lua(manifest)})
