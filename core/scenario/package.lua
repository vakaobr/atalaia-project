--
-- The compiled scenario package (kind: scenario, decision P4R7): mode.yaml and
-- field.lua.
--
-- mode.yaml carries what the controller and the app need to show the scenario
-- without reading its Lua: the names in English and Portuguese, the scenario's
-- parameters, and under `scenario` the boxes' language, the teams, the squads,
-- the nodes the GM assigns (P4R8) and every objective's id, type, names,
-- assignee, visibility, dependencies and points (for the per-team routing and
-- the player view). Codes and destinations are only in field.lua, which only
-- staff read.
local package = {}

local py = need("py")
local m = need("manifest")
local luagen = need("luagen")
local yaml = need("yaml")

local ordered, or_map, copy_list = luagen.ordered, luagen.or_map, luagen.copy_list

local function copy_map(v)
  local out = py.map()
  for i = 1, v.n do
    py.put(out, v.k[i], v.v[i])
  end
  return out
end

-- The translations of an entry's texts: { lang: { key: text } } for the keys given.
local function texts(entry, keys)
  local out = py.map()
  local i18n = or_map(py.get(entry, "i18n"))
  for i = 1, i18n.n do
    local lang, strings = i18n.k[i], i18n.v[i]
    local picked = py.map()
    for _, k in ipairs(keys) do
      if py.truthy(py.get(strings, k)) then
        py.put(picked, k, py.get(strings, k))
      end
    end
    if picked.n > 0 then
      py.put(out, lang, picked)
    end
  end
  return out
end

local function objective_meta(o)
  local assignee = or_map(py.get(o, "assignee"))
  local effect = or_map(py.get(o, "effect"))
  local meta = ordered("id", py.get(o, "id"), "type", py.get(o, "type"), "name", py.get(o, "name"))
  if py.truthy(py.get(o, "description")) then
    py.put(meta, "description", py.get(o, "description"))
  end
  local t = texts(o, { "name", "description" })
  if t.n > 0 then
    py.put(meta, "i18n", t)
  end
  if py.get(assignee, "team") ~= nil then
    py.put(meta, "team", py.get(assignee, "team"))
  end
  if py.get(assignee, "squad") ~= nil then
    py.put(meta, "squad", py.get(assignee, "squad"))
  end
  py.put(meta, "visibility", py.getd(o, "visibility", m.default_visibility(o)))
  if py.get(o, "target") ~= nil then
    py.put(meta, "target", py.get(o, "target"))
  end
  if py.truthy(py.get(o, "depends_on")) then
    py.put(meta, "depends_on", copy_list(py.get(o, "depends_on")))
  end
  if py.truthy(py.get(effect, "reveal")) then
    py.put(meta, "reveals", copy_list(py.get(effect, "reveal")))
  end
  if py.get(effect, "points") ~= nil then
    -- The manifest's own object: a points map two objectives share (a YAML
    -- alias) is written once, with an anchor, as PyYAML does.
    py.put(meta, "points", py.get(effect, "points"))
  end
  if py.truthy(py.get(effect, "win")) then
    py.put(meta, "win", true)
  end
  if py.truthy(py.get(o, "time_window")) then
    py.put(meta, "time_window", copy_map(py.get(o, "time_window")))
  end
  return meta
end

local HEAD = "# "
  .. luagen.SPDX_TAG
  .. " "
  .. luagen.LICENSE
  .. "\n"
  .. "#\n"
  .. "# Generated by the Atalaia scenario compiler (controller/atalaia_controller/scenarios) from a\n"
  .. "# scenario manifest: a scenario package (kind: scenario, decision P4R7) that leads the game's id,\n"
  .. "# <this id>+"
  .. m.OBJECTIVES_PACKAGE
  .. ". Compile the manifest again rather than editing this file.\n"

function package.mode_yaml(manifest)
  local doc = ordered(
    "id",
    py.get(manifest, "id"),
    "version",
    py.str(py.get(manifest, "version")),
    "license",
    luagen.LICENSE,
    "kind",
    "scenario",
    "name",
    py.get(manifest, "name")
  )
  if py.truthy(py.get(manifest, "description")) then
    py.put(doc, "description", py.get(manifest, "description"))
  end
  if py.truthy(py.get(manifest, "author")) then
    py.put(doc, "author", py.get(manifest, "author"))
  end
  local params = py.get(manifest, "params")
  if py.truthy(params) then
    local out = py.map()
    for i = 1, params.n do
      py.put(out, params.k[i], copy_map(params.v[i]))
    end
    py.put(doc, "params", out)
  end
  local t = texts(manifest, { "name", "description", "params" })
  if t.n > 0 then
    py.put(doc, "i18n", t)
  end
  local nodes = py.map()
  local raw = or_map(py.get(manifest, "nodes"))
  for i = 1, raw.n do
    py.put(nodes, raw.k[i], copy_map(raw.v[i]))
  end
  local objectives = py.list({}, 0)
  local src = py.get(manifest, "objectives")
  for i = 1, src.n do
    objectives[i] = objective_meta(src[i])
  end
  objectives.n = src.n
  local teams = py.getd(manifest, "teams", nil)
  py.put(
    doc,
    "scenario",
    ordered(
      "lang",
      py.getd(manifest, "lang", "pt"),
      "teams",
      teams ~= nil and copy_list(teams) or py.list({ "red", "blue" }, 2),
      "squads",
      py.getd(manifest, "squads", 0),
      "nodes",
      nodes,
      "objectives",
      objectives
    )
  )
  return HEAD .. yaml.dump(doc)
end

-- The package of a manifest that validated without errors: its id, version and files.
function package.build(manifest, runtime)
  return {
    id = py.get(manifest, "id"),
    version = py.str(py.get(manifest, "version")),
    mode_yaml = package.mode_yaml(manifest),
    field_lua = luagen.field_lua(manifest, runtime),
  }
end

return package
